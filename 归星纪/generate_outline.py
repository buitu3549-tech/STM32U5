FONT = '宋体'

def run(para, text, size=12, bold=False, color=None):
    r = para.add_run(text)
    r.font.size = Pt(size)
    r.font.name = FONT
    r.font.bold = bold
    r._element.rPr.rFonts.set('{http://schemas.openxmlformats.org/wordprocessingml/2006/main}eastAsia', FONT)
    if color:
        r.font.color.rgb = color
    return r

def add(doc, text, size=12, bold=False, align=None, indent=True, color=None, spacing_after=0):
    p = doc.add_paragraph()
    p.paragraph_format.line_spacing = 1.5
    p.paragraph_format.space_before = Pt(0)
    p.paragraph_format.space_after = Pt(spacing_after)
    if indent:
        p.paragraph_format.first_line_indent = Pt(24)
    if align is not None:
        p.alignment = align
    run(p, text, size=size, bold=bold, color=color)
    return p

def add_blank(doc):
    p = doc.add_paragraph()
    p.paragraph_format.space_before = Pt(0)
    p.paragraph_format.space_after = Pt(0)
    return p

def add_bold_lead(doc, lead, body):
    """Add a paragraph with a bold lead-in followed by normal text."""
    p = doc.add_paragraph()
    p.paragraph_format.line_spacing = 1.5
    p.paragraph_format.space_before = Pt(0)
    p.paragraph_format.space_after = Pt(0)
    p.paragraph_format.first_line_indent = Pt(24)
    run(p, lead, size=12, bold=True)
    run(p, body, size=12)
    return p

