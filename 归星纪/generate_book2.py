FONT_NAME = "宋体"

def add_title(text, size=16, bold=True, align=WD_ALIGN_PARAGRAPH.CENTER):
    p = doc.add_paragraph()
    p.alignment = align
    r = p.add_run(text)
    r.font.size = Pt(size)
    r.font.bold = bold
    r.font.name = FONT_NAME
    r._element.rPr.rFonts.set("{http://schemas.openxmlformats.org/wordprocessingml/2006/main}eastAsia", FONT_NAME)
    return p

def add_subtitle(text, size=10, color=RGBColor(128,128,128)):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = p.add_run(text)
    r.font.size = Pt(size)
    r.font.color.rgb = color
    r.font.name = FONT_NAME
    r._element.rPr.rFonts.set("{http://schemas.openxmlformats.org/wordprocessingml/2006/main}eastAsia", FONT_NAME)
    return p

def add_body(text, size=12, bold=False, indent=True, space_before=0, space_after=6):
    p = doc.add_paragraph()
    if indent:
        p.paragraph_format.first_line_indent = Pt(24)
    p.paragraph_format.space_before = Pt(space_before)
    p.paragraph_format.space_after = Pt(space_after)
    p.paragraph_format.line_spacing = 1.5
    r = p.add_run(text)
    r.font.size = Pt(size)
    r.font.bold = bold
    r.font.name = FONT_NAME
    r._element.rPr.rFonts.set("{http://schemas.openxmlformats.org/wordprocessingml/2006/main}eastAsia", FONT_NAME)
    return p

def add_blank():
    doc.add_paragraph()

def add_separator():
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = p.add_run("— — —")
    r.font.size = Pt(10)
    r.font.color.rgb = RGBColor(180, 180, 180)
    r.font.name = FONT_NAME

def add_code_block(text, size=10):
    for line in text.split("\n"):
        add_body(line, size=size, indent=False, space_before=0, space_after=0)

