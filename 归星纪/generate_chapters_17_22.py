ch17_title = "选择"
ch17_content = """从程远那里回来之后，林澈有两天没说话。

不是故意不说话。是喉咙里像塞了一块东西。吞不下去，吐不出来。他知道那是什么——是程远说的那些话。关于扫描周期。关于两小时四十七分钟。关于"降权"。关于一个人在系统里被慢慢调低优先级，直到所有人都不再看得到他。

这些话没有消失。林澈反复确认过。他在手机备忘录里打了一遍。锁屏。再打开。还在。又打了一遍。又锁屏。又在。字没有变。间距没有变。他盯着屏幕看了很久，不知道自己在等什么。也许是等它们被删掉。但它们没有。

它们是程远说的。不是他说的。他只是在听。也许"听"不算犯规。也许"记得别人说的话"不在扫描范围之内。也许。

也可能是扫描还没轮到他。

这两天里他照常上课。照常去食堂。照常在晚自习写作业。张昊跟他说话他就应。许静在后面喊他他就回头。一切正常。正常到他觉得不正常。他第一次意识到，"正常"是一种可以伪装的东西。你只要做所有人都在做的事，看起来就像所有人。看起来。

第二天下午。体育课。自由活动时间。林澈没有打球，没有回教室。他上了天台。

天台还是老样子。水塔在左边，铁栏杆锈了一截，地上有几截被晒裂的木头。水泥围栏被午后的太阳烤得发烫，手放上去停不过三秒。操场在下面。跑道上有几个班在跑步。体育老师的哨子一短一长。远处是那排居民楼，有人在阳台上晾被单。被单被风吹得一鼓一鼓的。

林澈靠着围栏坐下。水泥地的热度隔着校服裤子透上来。他抬头看天。云很少。天蓝得很薄。飞机尾迹都没有。

他在想许知夏。

不是想她的长相。是想那个感觉——有人趁你不注意在你课本上画了一个鸟窝头涂鸦的感觉。那种随意。那种"反正明天还会见面"。她不觉得需要郑重其事。她以为时间还很多。她以为明天还会来。

然后明天没有来。然后没有人记得她来过。

林澈把手指伸进裤兜里。指尖碰到一个东西——那张便利贴。从程远墙上撕下来的那张。上面的字已经全没了。现在就是一张普通的黄色便利贴。背面有一点点残留的胶。他把便利贴翻过来。对着阳光。什么都没了。连那个"澈"字的最后一笔都没有了。

程远也被删除了。

不是程远这个人——至少现在还不是。是他写下的那些字。他的记录。他花了三年时间一笔一划写上去的名字。那面墙。那些不同颜色的笔。那些"一横。"一竖。"一撇。"一捺"。全部变成了空白。一个高中生花了三年建立的反遗忘系统，在系统面前连一周都没撑住。

林澈把便利贴放回兜里。

他想起程远最后说的那句话："你还没被标记。等你被标记了，你就会希望自己什么都不知道。"

但林澈已经知道了。他知道了许知夏的存在。知道了程远姐姐的存在。知道了三十七个名字。知道了两小时四十七分钟。知道了87.5兆赫。这些东西已经在他的脑子里了。没办法假装不知道。就算他现在闭嘴——就算他从今天起一个字都不问、一个人都不提起——这些东西还在。它们已经长进去了。像一棵树的根扎进了地基。拔出来，房子也会塌。

这就是选择。

不是"要不要查下去"。是"要不要假装正常"。要不要像程远说的那样，把自己藏进一个沉默的壳里，等着系统下一次扫描的时候跳过自己。程远选了这条路。他藏了三年。他还在。"还在"的意思是他还没被删——但他的记录没了。他的墙空了。他的便利贴变成了黄纸。他的沉默没有救回姐姐。只是让他自己暂时安全。

暂时。

林澈不想这样。不是因为他勇敢。是因为他觉得自己已经被看到了。从他在花名册上查那个空位开始。从他问班主任"这个座位以前是谁"开始。从他第一次听到87.5兆赫的那个女声念他的名字开始。

他不是在"决定要不要开始"。是已经开始了。

太阳往西边挪了一点。操场上跑步的班级散了，换了一群在草坪上坐着聊天的女生。她们的裙子被风吹起来一点，又落下去。笑声断断续续地飘上来。很远。很轻。像隔着水。

林澈站起来。腿麻了。他用拳头敲了敲膝盖。围栏上他刚才靠过的地方留了一小片汗印。太阳照上去，慢慢变浅。

他推开通往走廊的门。

走廊很长。声控灯没有亮——日光还够。走廊尽头是楼梯间。楼梯间再过去是教学楼另一翼。那边有实验室、音乐教室、一间常年锁着的资料室。林澈从没去过资料室。他只知道门上贴了一张泛黄的封条。封条上的字已经看不太清了。

走廊里没有人。两边教室的门都开着。里面的课桌歪歪斜斜地排着。黑板上有上一节课的板书，没擦干净。值日生的名字写在黑板角落：周颖。林澈不认识这个人。可能是一年级的。

他往前走。脚步声在地砖上发出干燥的、轻微的摩擦。走了大概二十步，他停下来。

因为他听到了一个声音。

不是从前面来的。不是从后面来的。是从上面。

天花板上方。有什么东西在移动。很慢。不是老鼠——老鼠的爪子尖，声音是碎的。这个声音是连续的。平滑的。像一个重物被什么东西拖着，从天花板上面经过。

声音从林澈头顶过去了。然后停在走廊另一端。停了大概三秒钟。

然后声控灯亮了。

不是一盏。是走廊尽头的三盏灯，由远及近，一盏一盏亮起来。没有人经过。没有任何脚步声。灯自己亮了。像有什么东西从走廊那头走了过来。走到了林澈面前大概三米的地方。停住了。

灯没有灭。

林澈站在原地看着那三盏亮着的灯。日光灯的白光照在地砖上，把灰尘照得一清二楚。那些灰尘悬浮在光柱里，缓慢地旋转。三米之外是三盏灯。三米之外什么也没有。但灯亮着。像有人站在那里，等着他走过去。

林澈没有走过去。他转身，推开旁边的教室门。教室里空的。窗帘被卷起来，在风里一鼓一鼓的。他穿过教室，从另一个门出去了。

身后那三盏灯还亮着。亮了很久。

然后灭掉了。不是同时灭的——先是最近的那盏。然后是中间那盏。然后是最远的那盏。一盏接一盏。像有人在走廊里走远了。"""

