"""
Generate chapters 17-22 of 归星纪 as .docx files.
"""
import os
from docx import Document
from docx.shared import Pt, Cm
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.oxml.ns import qn

OUTPUT_DIR = "E:/项目/归星纪/未定义文明/章节正文"

def create_docx(chapter_num, title, content):
    doc = Document()

    # Set default font
    style = doc.styles['Normal']
    font = style.font
    font.name = '宋体'
    font.size = Pt(12)
    style.element.rPr.rFonts.set(qn('w:eastAsia'), '宋体')

    # Set paragraph format for normal style
    pf = style.paragraph_format
    pf.line_spacing = 1.5
    pf.first_line_indent = Cm(0.74)  # ~2 Chinese characters

    # Title
    title_para = doc.add_paragraph()
    title_para.alignment = WD_ALIGN_PARAGRAPH.CENTER
    title_para.paragraph_format.first_line_indent = Cm(0)
    title_para.paragraph_format.space_after = Pt(6)
    title_run = title_para.add_run(f"第{chapter_num:03d}章　{title}")
    title_run.bold = True
    title_run.font.size = Pt(16)
    title_run.font.name = '宋体'
    title_run._element.rPr.rFonts.set(qn('w:eastAsia'), '宋体')

    # Subtitle
    sub_para = doc.add_paragraph()
    sub_para.alignment = WD_ALIGN_PARAGRAPH.CENTER
    sub_para.paragraph_format.first_line_indent = Cm(0)
    sub_para.paragraph_format.space_after = Pt(12)
    sub_run = sub_para.add_run("归星纪 · 第一部 · 未定义文明")
    sub_run.font.size = Pt(10)
    sub_run.font.name = '宋体'
    sub_run.font.color.rgb = None
    sub_run._element.rPr.rFonts.set(qn('w:eastAsia'), '宋体')

    # Content paragraphs
    for para_text in content.split('\n\n'):
        para_text = para_text.strip()
        if not para_text:
            continue
        if para_text == '---':
            # Section break
            sep_para = doc.add_paragraph()
            sep_para.alignment = WD_ALIGN_PARAGRAPH.CENTER
            sep_para.paragraph_format.first_line_indent = Cm(0)
            sep_para.paragraph_format.space_before = Pt(6)
            sep_para.paragraph_format.space_after = Pt(6)
            sep_run = sep_para.add_run('—')
            sep_run.font.size = Pt(10)
            sep_run.font.name = '宋体'
            sep_run._element.rPr.rFonts.set(qn('w:eastAsia'), '宋体')
        else:
            para = doc.add_paragraph()
            para.paragraph_format.line_spacing = 1.5
            para.paragraph_format.first_line_indent = Cm(0.74)
            run = para.add_run(para_text)
            run.font.name = '宋体'
            run.font.size = Pt(12)
            run._element.rPr.rFonts.set(qn('w:eastAsia'), '宋体')

    # Footer with chapter info
    footer_para = doc.add_paragraph()
    footer_para.alignment = WD_ALIGN_PARAGRAPH.RIGHT
    footer_para.paragraph_format.first_line_indent = Cm(0)
    footer_para.paragraph_format.space_before = Pt(24)
    footer_run = footer_para.add_run(f"（第{chapter_num:03d}章 完）")
    footer_run.font.size = Pt(10)
    footer_run.font.name = '宋体'
    footer_run._element.rPr.rFonts.set(qn('w:eastAsia'), '宋体')

    filename = f"第{chapter_num:03d}章-{title}.docx"
    filepath = os.path.join(OUTPUT_DIR, filename)
    doc.save(filepath)
    print(f"Saved: {filepath}")

