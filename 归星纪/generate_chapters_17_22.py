ch18_title = "胡老师"
ch18_content = """周一早自习。班主任老陈领进来一个人。

女的。四十出头。穿深灰色西装外套，里面白衬衫，扣子扣到最上面一颗。头发扎得很紧，发际线往后拉，让她的眉毛看起来微微上挑。她站在讲台旁边，手里攥着一个深蓝色的文件夹。文件夹很旧了，边角磨得发亮。

"这是新来的语文老师，"老陈说，"胡老师。你们原先的语文老师请了产假，这个学期由胡老师代课。"

老陈说完就走了。胡老师站在讲台上，把文件夹放在讲台上，没有马上打开。她扫了一遍全班。从左到右。从上到下。林澈坐在第三排靠走廊的位置。她的目光扫过他——然后继续往右。没有停留。没有跳过。就是正常地、匀速地看过去。像他和其他人没什么不同。

但林澈注意到一件事。她扫视的速度太均匀了。均匀到不自然。正常人的目光扫过一个教室，会在某几张脸上短暂地停一下——可能是某个长得像熟人的学生，某个坐姿特别的孩子，或者某个正在盯着她看的人。不会有人把所有脸都用完全相同的速度扫过去。一个都不会多停。一个都不会少看。

"打开课本第六十三页，"胡老师说。她的声音很平，不带感情，但咬字异常清楚。每个字之间间隔完全一样。不是一个语文老师读课文的那种抑扬顿挫——是像有人在用嗓子朗读一个数据库里的文本。

"《陈情表》。"

教室里一片翻书的声音。张昊在抽屉里翻了半天，课本压在数学练习册底下。林澈把自己的课本往右边推了一点，让他合看。

"臣密言——"胡老师开始读。

读得不对。不是说有错别字——每个字都是对的。但断句不对。正常的语文老师读《陈情表》会在逗号处停半拍，在句号处停一拍，在情感的转折处——"臣以险衅，夙遭闵凶"——会自然地放低、放缓。胡老师不是这样。她像在数拍子。每个逗号停一拍。每个句号停两拍。不管什么内容。不管什么情感。"生孩六月，慈父见背"跟"既无伯叔，终鲜兄弟"的停顿完全一样。

林澈听着听着觉得冷。不是体感的冷。是那种你发现一件很正常的事情里面有某个细节不对时，汗毛微微竖起来的感觉。

"你在听吗？"张昊用胳膊肘撞了他一下。

"在听。"

"这个老师好怪。"

林澈没有说话。

下课后，胡老师没有像其他老师那样在教室里走一圈。她收起文件夹，直接走了。走到门口的时候，她回头看了林澈一眼。就一眼。很快。然后走了。

就那一眼，林澈觉得她的眼神跟刚才扫视全班时不一样。不是"注视"——是"确认"。她不是在看林澈这个人。她是在确认某个参数。像在扫描一个条形码，确认了这个条形码对应的是哪条数据。

下午第二节课。胡老师又来上语文课。这节课讲的是课后习题。她站在讲台上一道一道地对答案。标准答案一个不错。字字都对。讲"臣侍汤药"的真实含义时，她忽然加进了一段历史背景——不是教材上的。是某种更古老、更偏门的文献来源。她讲得很细。细到数字——李密写这篇表的时候祖母多大年纪、他多大年纪、当时的皇帝多大年纪。细到日子。

"泰始三年二月初九。"胡老师说。"李密祖母刘氏卒。距李密上表——四年零七个月。"

教室里安静了一瞬。张昊小声说了一句"牛"。林澈没觉得牛。他觉得不对。

正常老师讲古文不会精确到月。不会"四年零七个月"。这是一种奇怪的精确感——不是学问好，是某种强迫式的格式感。像有人必须把所有东西都对齐到同一个度量衡里。

林澈想起程远姐姐说过的话："它在算我。"身高。体重。心率。每天说的话。每次笑。每次沉默。所有参数被拆成数字放进一张表里，一个一个地核对。它不是在"认知"你——它是在"格式化"你。把你从一个人变成一个数据条目。然后那个条目如果不符合它的规则——就删除。

胡老师讲课的节奏也是这样的。

她不是一个人。或者——她曾经是。但现在不是了。

下课铃响了。胡老师准时合上课本。不早一秒。不晚一秒。

林澈看着她走出教室。她的脚步也很均匀。鞋跟敲在水磨石地面上的声音——嗒嗒嗒——间距完全一致。

林澈低头看了一眼自己的课本。这一页是空白。他没记任何笔记。他转头看了一眼张昊的课本——张昊记了一页密密麻麻的字。张昊的笔记一直很烂，但这节课他记得整齐得不像他自己写的。每个字都在格子里。横是横，竖是竖。没有潦草。

"你笔记记得挺好的。"林澈说。

"嗯。"张昊看着自己写的笔记，皱了一下眉，然后把课本合上了。他的表情很奇怪——不是得意。是想不起来自己什么时候写的。

晚饭。食堂。林澈一个人。张昊去打球了，许静回宿舍洗头。他坐在角落的桌子旁，面前是一盘炒面和一碗免费汤。汤里的蛋花稀稀拉拉的，浮在汤面上像几缕黄色的棉絮。

旁边那桌有人在聊天。说的是胡老师——"那个新来的语文老师好认真""上课全是干货""听她讲课感觉像在听AI"。最后这句话让几个人笑了。笑完没人再接这个茬。

林澈回到教室。晚自习。

他翻开语文课本第六十三页。白天胡老师读过的那些字还在。他的手指顺着字迹一行一行地摸过去。纸是平的。墨是干的。但他觉得那些字比早上更整齐了。不是错觉——有几个地方他记得原来是歪的。课本印得不太认真，有几行字微微向下倾斜。但现在那些字全在一条直线上。印刷体。完美对齐。

林澈把课本合上。

晚自习下课。他去办公室找老陈。办公室只剩老陈一个人，坐在桌前看手机。桌角放着一杯泡了太久的茶，茶叶沉在杯底，茶水变成了浑浊的褐色。

"陈老师，胡老师是从哪调来的？"

老陈抬起头，把手机翻过来扣在桌上。"怎么突然问这个？"

"随便问问。"

老陈想了一下。然后皱了一下眉。他的嘴张开，又闭上。手指无意识地敲了一下茶杯的边缘。茶水的表面晃了一下。

"她是……"老陈停住了。"她应该是……"

"是？"

"她说过的。"老陈的声音变得不那么确定了。"她从……一个学校调过来的。我记一下——"他去翻手机上的人事群聊记录。翻了很久。一直在往前翻。

"找到了吗？"

老陈没有回答。他把手机放下，端起茶杯喝了一口。茶已经凉透了。他放下杯子的时候杯底磕了一下桌面，发出一声闷响。

"实验小学来的，"他说，声音恢复了正常。"对。实验小学。教了几十年了。"

林澈没有纠正他。老陈刚才说的是"小学"——他们这是高中。

走出办公室的时候，走廊的声控灯亮了。一盏接一盏。跟在林澈身后。他没有回头。他加快脚步。灯也跟着加快。

他跑了起来。灯没有跑——它们只是亮着。一直亮着。像有什么东西在他身后，用一个恒定的距离跟着他。不快。不慢。"""

